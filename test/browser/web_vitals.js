// Run with playwright-cli run-code "$(cat test/browser/web_vitals.js)" against bin/dev.
// Local response fixtures expose a dummy host-gated target; all external traffic is stubbed.
async () => {
  for (const other of page.context().pages()) if (other !== page) await other.close()
  await page.bringToFront()
  await page.setViewportSize({ width: 1360, height: 900 })
  await page.context().unrouteAll()
  await page.evaluate(() => localStorage.removeItem("stuttgart-live-consent-v1"))
  const errors = [], failures = [], chunks = []
  page.on("pageerror", error => errors.push(error.message))
  page.on("requestfailed", request => failures.push({ url: request.url(), error: request.failure()?.errorText }))
  page.on("response", response => { if (response.status() >= 400) failures.push({ url: response.url(), status: response.status() }) })
  page.on("request", request => { if (/web-vitals-.*\.js/.test(request.url())) chunks.push(request.url()) })
  await page.context().route("**/*", async route => {
    const url = new URL(route.request().url())
    if (url.origin !== "http://localhost:3000") return route.fulfill({ status: 200, contentType: "application/javascript", body: "" })
    if (route.request().method() !== "GET" || /^\/(session|passwords)/.test(url.pathname)) return route.continue()
    if (route.request().resourceType() !== "document" && route.request().headers()["accept"]?.includes("text/html") !== true) return route.continue()
    const response = await route.fetch()
    const html = await response.text()
    return route.fulfill({ response, body: html.replace('data-controller="consent scroll-top"', 'data-controller="consent scroll-top" data-consent-measurement-id-value="G-TASK7"') })
  })
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const metrics = () => page.evaluate(() => (window.dataLayer || []).map(args => Array.from(args)).filter(args => args[0] === "event" && args[1] === "web_vital").map(args => args[2]))
  await page.goto("http://localhost:3000/search?q=private-search")
  await page.evaluate(() => localStorage.removeItem("stuttgart-live-consent-v1"))
  await page.reload()
  await page.waitForTimeout(400)
  check(chunks.length === 0, "denied consent imported metrics")
  // A real Turbo visit precedes the FIRST grant; hard-navigation paint belongs to /search.
  await page.evaluate(() => { window.task7Document = "original"; window.Turbo.visit("/news") })
  await page.waitForURL("**/news")
  await page.locator('body[data-consent-measurement-id-value="G-TASK7"]').waitFor()
  await page.locator('.consent-banner button[data-action="click->consent#acceptAll"]').click()
  await page.waitForFunction(() => (window.dataLayer || []).some(args => args[1] === "web_vital"))
  await page.evaluate(() => {
    const button = document.createElement("button")
    button.id = "task7-interaction"; button.textContent = "Test interaction"
    button.style.cssText = "position:fixed;top:100px;left:10px;z-index:99999"
    button.addEventListener("click", () => { const start = performance.now(); while (performance.now() - start < 90) {} })
    document.body.append(button)
  })
  await page.locator("#task7-interaction").click()
  await page.waitForTimeout(650)
  await page.evaluate(() => { document.querySelector("main").style.marginTop = "150px" })
  await page.waitForTimeout(700)
  // Visibility flushes CLS/INP; a tab switch is an actual browser visibility transition.
  const other = await page.context().newPage(); await other.goto("http://localhost:3000/icon.svg")
  await other.bringToFront(); await page.waitForTimeout(200); await page.bringToFront()
  const recorded = await metrics()
  check(chunks.length === 1, `expected one metrics import, got ${chunks.length}`)
  check(await page.evaluate(() => window.task7Document) === "original", "Turbo performed a hard navigation")
  check(["LCP", "INP", "CLS", "FCP", "TTFB"].every(name => recorded.some(metric => metric.metric_name === name)), `missing real metric: ${JSON.stringify(recorded)}`)
  check(recorded.every(metric => metric.route_pattern === "/search" && metric.page_location === "/search" && metric.page_title === "" && metric.page_referrer === ""), "unsafe or incorrect document context")
  check(!/private-search|https?:|entries|element/.test(JSON.stringify(recorded)), "private data in metric payload")
  await page.getByRole('button', { name: 'Menü öffnen', exact: true }).click()
  await page.locator('.design-preview-menu-privacy-button').click()
  await page.locator('#consent-analytics').uncheck()
  await page.locator('button[data-action="click->consent#savePreferences"]').click()
  await page.waitForFunction(() => window.StuttgartLiveConsent.preferences.analytics === false)
  const before = (await metrics()).length
  await page.locator("#task7-interaction").click()
  await page.waitForTimeout(300)
  check((await metrics()).length === before, "reports continued after revocation")
  check(await page.evaluate(() => JSON.parse(localStorage.getItem("stuttgart-live-consent-v1")).analytics) === false, "revocation not persisted")
  await page.reload(); await page.waitForTimeout(250)
  check((await metrics()).length === 0 && chunks.length === 1, "saved denied state imported/reported")
  await page.goto("http://localhost:3000/session/new")
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.locator('script[src*="/backend"]').count() === 1 && await page.locator('script[src*="/public"]').count() === 0, "login assets incorrect")
  check(await page.locator(".consent-banner, [data-controller~=consent]").count() === 0, "inert auth consent UI")
  const nav = page.locator('.app-nav-toggle')
  await nav.click(); check(await nav.getAttribute("aria-expanded") === "true", "mobile navigation failed")
  await page.getByLabel("E-Mail", { exact: false }).fill("task7-invalid@example.invalid")
  await page.locator('input[type="password"]').fill("invalid-password")
  await page.locator('input[type="submit"]').click()
  await page.locator("#flash-messages [role=alert]").waitFor()
  check(await page.locator("#flash-messages").innerText() !== "", "login flash missing")
  await page.goto("http://localhost:3000/passwords/new")
  check(await page.locator('script[src*="/backend"]').count() === 1, "forgot-password assets incorrect")
  check(await page.locator('form input[type="email"]').count() === 1, "forgot-password form missing")
  check(errors.length === 0, `JS errors: ${errors}`)
  check(failures.length === 0, `resource failures: ${JSON.stringify(failures)}`)
  await other.close()
  return { result: "PASS", metrics: recorded, chunkRequests: chunks.length, errors, failures, consent: "denied → Turbo → granted → revoked → saved denied", auth: "login/forgot assets, mobile navigation, invalid-login flash" }
}
